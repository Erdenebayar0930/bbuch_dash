/**
 * Процессын түвшний хамгаалалт — Next.js энэ файлыг сервер асахад НЭГ УДАА
 * дуудна.
 *
 * ЯАГААД ХЭРЭГТЭЙ ВЭ: Node 20-д баригдаагүй Promise-ийн алдаа нь процессыг
 * ШУУД УНАГААНА (`--unhandled-rejections=throw` нь анхдагч). Тэр үед апп
 * бүхэлдээ унаж, прокси нь 502 өгнө — хэрэглэгчийн зүгээс "сервер унасан"
 * гэж харагдана. Route бүрийн `try/catch` нь дуусаагүй фон ажлыг (жишээ нь
 * `void backfillClaimsIfStale(...)`) хамгаалж чадахгүй.
 *
 * Энэ бүртгэгч нь тийм алдааг НОМЕР НЭГ логт бичээд процессыг амьд үлдээнэ.
 * Ганц хүсэлт эвдэрсэн нь бүх хэрэглэгчийг унагаах шалтгаан болох ёсгүй.
 *
 * ⚠ `uncaughtException`-ыг залгих нь эрсдэлтэй гэж үздэг — процессын төлөв
 * гэмтсэн байж болно. Гэвч shared hosting дээр процессыг Passenger л сэргээдэг
 * бөгөөд тэр нь дараагийн хүсэлт ирэх хүртэл хийгддэггүй. Тиймээс "унасан ч
 * чимээгүй" байхаас "амьд бөгөөд логтой" нь энэ орчинд илүү найдвартай.
 * Санах ой гэмтэх төрлийн алдаанд `max_memory_restart`-ын үүргийг Passenger
 * өөрөө гүйцэтгэнэ.
 */
export async function register() {
  // Зөвхөн Node.js runtime дээр — Edge дээр process эвент байхгүй
  if (process.env.NEXT_RUNTIME !== "nodejs") return;

  process.on("unhandledRejection", (reason) => {
    console.error("[process] баригдаагүй Promise алдаа:", reason);
  });

  process.on("uncaughtException", (error) => {
    console.error("[process] баригдаагүй алдаа:", error);
  });

  /**
   * Гарах шалтгааныг тэмдэглэнэ — Passenger процессыг дахин асаахад логт
   * "яагаад" гэдэг нь үлдэнэ. Үүнгүйгээр restart нь ул мөргүй болно.
   */
  process.on("SIGTERM", () => {
    console.log("[process] SIGTERM — зогсож байна");
  });
}
